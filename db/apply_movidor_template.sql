-- =============================================================================
-- APPLY EVERYTHING TO THE RRD MOVIDOR TEMPLATE
--
-- One script, run top to bottom, that brings a RP_config database up to the
-- agreed definition of RRD-MOVIDOR-TEMPLATE. Safe to run more than once: every
-- part is an idempotent UPDATE or an insert guarded by IF NOT EXISTS.
--
--   Part 1  Sections          51 parameters get their "Step > Group" section
--   Part 2  Activation rules  condition + quantity formulas for 21 rules
--   Part 3  Missing rules     RRD-63 / RRD-64, inserted only if absent
--   Part 4  Report            what the database looks like afterwards
--
-- Wrapped in a single transaction. If any part fails nothing is applied -- a
-- half-configured rule set is worse than an unchanged one.
--
-- GENERATED by scratchpad/gen_master.py from rrd_movidor_sections.csv and
-- set_activation_rule_formulas.sql, so the row lists cannot drift from them.
--
-- BEFORE RUNNING: take a backup. db/backups/ holds point-in-time snapshots.
--
-- Every formula in Part 2 was checked against
-- backend/app/pricing_rules/movidor_upgrade_rules.py over 400 randomised
-- configurations with no mismatches. uCfgRules does not price quotes yet, so
-- this changes no live price -- it makes the data match the code.
-- =============================================================================

SET NOCOUNT ON;
SET XACT_ABORT ON;
