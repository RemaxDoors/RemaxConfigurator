END;

IF COL_LENGTH('dbo.uCfgParameters', 'Section') IS NULL
BEGIN
    RAISERROR('uCfgParameters.Section is missing. Run db/uCfg_add_section.sql (PART 1 ONLY - its part 2 overwrites sections with the old Streamlit names), then re-run this.', 16, 1);
    ROLLBACK TRANSACTION;
    RETURN;
END;

