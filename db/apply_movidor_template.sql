UPDATE r
SET r.ConditionFormula = f.CondFormula,
    r.QuantityFormula  = f.QtyFormula,
    r.QuantityUnit     = f.QtyUnit,
    r.Notes            = f.Note
FROM dbo.uCfgRules r
JOIN @F f ON f.RuleCode = r.RuleCode
WHERE r.CfgID = @Cfg;

DECLARE @RulesChanged INT = @@ROWCOUNT;

-- Refuse to half-apply. If a rule code is absent the two databases have
-- diverged, and quietly configuring the subset that happens to exist would
-- leave the rest firing on every quote with nobody the wiser.
DECLARE @Missing NVARCHAR(1000) = (
    SELECT STRING_AGG(f.RuleCode, ', ')
    FROM @F f
    WHERE NOT EXISTS (SELECT 1 FROM dbo.uCfgRules r
                      WHERE r.CfgID = @Cfg AND r.RuleCode = f.RuleCode)
);
IF @Missing IS NOT NULL
BEGIN
    RAISERROR('These rule codes are not in this database: %s. Nothing applied - reconcile the rule sets first.', 16, 1, @Missing);
    ROLLBACK TRANSACTION;
    RETURN;
END;

-- -- Part 3: rules in the M1 workbooks with no rule here -----------------------
-- Each is the missing half of a pair whose other half is configured, so the
-- part is simply never added to a quote. Both exist in M1 and price correctly.
IF NOT EXISTS (SELECT 1 FROM dbo.uCfgRules WHERE CfgID = @Cfg AND RuleCode = N'RRD-63')
BEGIN
    INSERT INTO dbo.uCfgRules
        (CfgID, RuleCode, Name, Category, ResultPartID, Quantity, QuantityUnit,
         ConditionFormula, Notes, IsActive)
    VALUES
        (@Cfg, N'RRD-63', N'ES40 Narrow Fascia', N'ASSEMBLY_UPGRADE',
         N'RRD-FASASS-ES40-3', N'1', N'Per Door', N'NUMDOORWIDTH <= 3000',
         N'Pairs with RRD-12 (> 3000). Width is in the formula because the operator list has no <=.', 1);

    DECLARE @R63 INT = (SELECT RuleID FROM dbo.uCfgRules WHERE CfgID = @Cfg AND RuleCode = N'RRD-63');
    INSERT INTO dbo.uCfgRuleConditions (RuleID, GroupNo, ControlName, Operator, CompareValue)
    VALUES (@R63, 1, N'CMBDOORMODEL',  N'equals', N'ES40'),
           (@R63, 1, N'CMBES40FASCIA', N'equals', N'Yes');
END;

IF NOT EXISTS (SELECT 1 FROM dbo.uCfgRules WHERE CfgID = @Cfg AND RuleCode = N'RRD-64')
BEGIN
    -- Inserted INACTIVE. A blank motor hand counts as Left in M1, so switching
    -- this on starts adding a cover to existing Concertina/Movifold quotes that
    -- specify the stainless shroud but no hand. Correct, but it moves prices --
    -- a deliberate act, not a side effect of running a script.
    INSERT INTO dbo.uCfgRules
        (CfgID, RuleCode, Name, Category, ResultPartID, ResultRevision,
         Quantity, QuantityUnit, Notes, IsActive)
    VALUES
        (@Cfg, N'RRD-64', N'Left-Hand Stainless-Steel Motor Cover',
         N'ASSEMBLY_UPGRADE', N'RRD-MOTCOV-CONC-LH', N'E', N'1', N'Per Door',
         N'Pairs with RRD-25 (right hand). A blank motor hand counts as Left, so this is the default cover.', 0);

    DECLARE @R64 INT = (SELECT RuleID FROM dbo.uCfgRules WHERE CfgID = @Cfg AND RuleCode = N'RRD-64');
    INSERT INTO dbo.uCfgRuleConditions (RuleID, GroupNo, ControlName, Operator, CompareValue)
    VALUES (@R64, 1, N'CMBDOORMODEL',   N'in',         N'MOVIFOLD, CONCERTINA'),
           (@R64, 1, N'CMBMOTORHAND',   N'not_equals', N'Right'),
           (@R64, 1, N'CMBMOTORSHROUD', N'equals',     N'Yes - Stainless Steel Upgrade');
END;

COMMIT TRANSACTION;

-- -- Part 4: report -----------------------------------------------------------
PRINT '--- Applied ---';
PRINT '  parameters re-sectioned : ' + CAST(@SectionsChanged AS VARCHAR);
PRINT '  rules given formulas    : ' + CAST(@RulesChanged AS VARCHAR);

SELECT Section, COUNT(*) AS Parameters
FROM dbo.uCfgParameters WHERE CfgID = @Cfg
GROUP BY Section ORDER BY Section;

SELECT r.RuleCode, r.Name, r.ResultPartID
FROM dbo.uCfgRules r
WHERE r.CfgID = @Cfg AND r.IsActive = 1
  AND (r.ConditionFormula IS NULL OR LTRIM(RTRIM(r.ConditionFormula)) = '')
  AND NOT EXISTS (SELECT 1 FROM dbo.uCfgRuleConditions c WHERE c.RuleID = r.RuleID)
ORDER BY r.RuleCode;

PRINT '';
PRINT 'The second result set is every ACTIVE rule with no condition and no';
PRINT 'condition formula - each one applies to every quote. Expect it empty.';
PRINT 'Restart the API afterwards if it was running before the change.';
